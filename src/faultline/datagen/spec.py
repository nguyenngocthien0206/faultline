"""What to generate: the dataset spec and the named volume profiles."""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import asdict, dataclass, replace
from datetime import date, timedelta
from typing import Any

DEFAULT_SEED = 42
DEFAULT_START_DATE = date(2026, 11, 1)


@dataclass(frozen=True)
class Profile:
    """A named size. Profiles only set volumes; everything else comes from the spec."""

    stores: int
    days: int
    orders_per_store_day: int
    members: int


PROFILES: dict[str, Profile] = {
    # Unit tests: big enough to contain every feature (refunds, price change,
    # store opening and closing, new members, tier upgrades), small enough to
    # generate in well under a second.
    "tiny": Profile(stores=4, days=4, orders_per_store_day=40, members=2_000),
    # `make demo`: a mid-sized chain over a month.
    "demo": Profile(stores=50, days=30, orders_per_store_day=300, members=20_000),
    # Performance runs: a large chain over a year (roughly 25M orders).
    "large": Profile(stores=200, days=365, orders_per_store_day=350, members=200_000),
}


@dataclass(frozen=True)
class DatasetSpec:
    """Everything that determines the generated bytes. Same spec, same output."""

    profile: str = "demo"
    seed: int = DEFAULT_SEED
    start_date: date = DEFAULT_START_DATE
    days: int = PROFILES["demo"].days
    stores: int = PROFILES["demo"].stores
    orders_per_store_day: int = PROFILES["demo"].orders_per_store_day
    members: int = PROFILES["demo"].members

    def __post_init__(self) -> None:
        for name in ("days", "stores", "orders_per_store_day", "members"):
            if getattr(self, name) < 1:
                raise ValueError(f"{name} must be at least 1, got {getattr(self, name)}")

    @classmethod
    def from_profile(cls, name: str, **overrides: Any) -> DatasetSpec:
        """Build a spec from a profile, then apply explicit overrides (None means keep)."""
        if name not in PROFILES:
            known = ", ".join(PROFILES)
            raise ValueError(f"unknown profile {name!r}, expected one of: {known}")
        spec = cls(profile=name, **asdict(PROFILES[name]))
        return replace(spec, **{k: v for k, v in overrides.items() if v is not None})

    @property
    def end_date(self) -> date:
        """Last generated day (inclusive)."""
        return self.start_date + timedelta(days=self.days - 1)

    def dates(self) -> Iterator[date]:
        for offset in range(self.days):
            yield self.start_date + timedelta(days=offset)

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["start_date"] = self.start_date.isoformat()
        return data
